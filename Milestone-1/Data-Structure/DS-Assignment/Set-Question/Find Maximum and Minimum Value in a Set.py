"""
Description: 
Finds the highest and lowest values in a numeric set 
using the built-in 'max()' and 'min()' functions.
"""

number_set = {15, 88, 3, 42, 99, 12}

max_val = max(number_set)
min_val = min(number_set)

print(f"Maximum value in the set: {max_val}")
print(f"Minimum value in the set: {min_val}")